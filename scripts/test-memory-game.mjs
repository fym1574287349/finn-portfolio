import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile(new URL('../app/components/memory-game.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { initialGame, gameReducer: reduce, shuffleDeck } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const deck = shuffleDeck(() => 0.5);
assert.equal(deck.length, 12);
assert.equal(new Set(deck.map(card => card.id)).size, 12);
for (let face = 1; face <= 6; face++) assert.equal(deck.filter(card => card.face === face).length, 2);
const start = () => reduce(initialGame, { type: 'start', deck, now: 1000 });
const flip = (state, id, now = 2000) => reduce(state, { type: 'flip', id, now });
let state = flip(start(), 0);
assert.deepEqual(flip(state, 0).open, [0], 'Cannot match a card to itself');
state = flip(state, 2);
assert.deepEqual(flip(state, 4).open, [0, 2], 'A third card cannot open');
assert.deepEqual(reduce(state, { type: 'tick', now: 2849 }).open, [0, 2]);
state = reduce(state, { type: 'tick', now: 2850 });
assert.deepEqual(state.open, [], 'Mismatch closes after 850ms');
state = flip(flip(start(), 0), 1);
assert.equal(state.matched.length * 5, 10);
assert.deepEqual(flip(state, 0).open, [], 'Matched cards remain matched');
for (let id = 2; id < 12; id += 2) state = flip(flip(state, id), id + 1);
assert.equal(state.phase, 'won');
assert.equal(state.matched.length * 5, 60);
assert.equal(reduce(state, { type: 'tick', now: 62000 }).phase, 'won');
state = reduce(start(), { type: 'tick', now: 60999 });
assert.equal(state.seconds, 1);
state = flip(state, 0, 61000);
assert.equal(state.phase, 'lost', 'Clicks at the deadline cannot score');
assert.equal(state.seconds, 0);
state = reduce(state, { type: 'start', deck: shuffleDeck(), now: 80000 });
assert.equal(state.phase, 'playing');
assert.equal(state.seconds, 60);
assert.equal(state.matched.length, 0);
assert.equal(state.deadline, 140000);
console.log('Passed: deck, matching, duplicate clicks, two-card lock, flip-back timing, win, timeout and replay.');
